def main():
    entries=source.index_pack()
    local=json.loads(source.read_asset(entries,'localization/zhs/cards.json'))
    cards=[]
    for original,desktop in zip(compose_cards.CARDS,BASE):
        asset,title,kind,rarity,cost,_=original
        skill,category,effect=desktop
        cards.append(dict(skill=skill,asset=asset,name=title,kind=kind,rarity=rarity,cost=cost,category=category,effect=effect))
    for asset,kind,rarity,cost,category,effect in EXTRA:
        cards.append(dict(skill=asset,asset=asset,name=local[asset.upper()+'.title'],kind=kind,rarity=rarity,cost=cost,category=category,effect=effect))
    for card in cards:
        assert card['name']==local[card['asset'].upper()+'.title']
        assert 'images/packed/card_portraits/defect/'+card['asset']+'.png.import' in entries
        card['game_rule_template']=local.get(card['asset'].upper()+'.description','')
    assert len(cards)==36 and len({c['skill'] for c in cards})==36
    (ROOT/'card_catalog.json').write_text(json.dumps(cards,ensure_ascii=False,indent=2),encoding='utf8')
    q=lambda value:json.dumps(value,ensure_ascii=False)
    rows=[', '.join(q(c[k]) for k in ['skill','asset','name','effect','category']) for c in cards]
    code='// Generated by expand_cards.py from the verified local game catalog.\nnamespace DefectCompanion { public static partial class GameArt { public static readonly CardInfo[] Cards = {\n'
    code+='\n'.join('new CardInfo('+row+'),' for row in rows)+'\n}; } }\n'
    (ROOT/'CardCatalog.Generated.cs').write_text(code,encoding='utf8')
    print('Verified',len(cards),'original card names and portrait assets')

if __name__=='__main__':main()
